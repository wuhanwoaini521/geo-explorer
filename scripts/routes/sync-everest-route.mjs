// 同步 Everest 南坡路线静态数据：design/world/everest-3d/route/ → miniprogram/data/routes/everest/south-col.json
//
// 说明（对应 Gate 2 约束）：
//  - 289 个真实路线控制点不硬编码进大型 TS 文件，保持独立 JSON/static data；
//  - 本脚本只做「搬运 + 形状校验 + 装配 provenance」，不做任何距离计算；
//    累计距离 / node.distanceM / node.progress 全部由运行时 RouteIndex builder 计算。
//  - 命令设计/产物可复现：设计数据文件已纳入 git（design/world/everest-3d/route/*.json）。
//
// 运行：
//   node scripts/routes/sync-everest-route.mjs
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const SRC_ROUTE = join(ROOT, "design/world/everest-3d/route/route-control-points.json");
const SRC_WAYPOINTS = join(ROOT, "design/world/everest-3d/route/waypoints.json");
const SRC_META = join(ROOT, "design/world/everest-3d/work/everest-terrain-metadata.json");
const OUT = join(ROOT, "miniprogram/data/routes/everest/south-col.json");
const OUT_TS = join(ROOT, "miniprogram/data/routes/everest/south-col.ts");

/** 规划里定好的基准 DEM 最小高程（m）—— 取自 everest-terrain-metadata.json elevation_min_m；
 *  因 work/ 目录默认 gitignore，构建机可读取则优先读取，否则回落到该文档化常数。 */
const FALLBACK_BASE_M = 2976.22;

const KIND_BY_ID = {
  "base-camp": "camp",
  "khumbu-icefall": "danger",
  "camp-i": "camp",
  "western-cwm-camp-ii": "camp",
  "lhotse-face-camp-iii": "camp",
  "south-col-camp-iv": "camp",
  "summit": "summit",
};

async function readJson(path) {
  try {
    return JSON.parse(await readFile(path, "utf8"));
  } catch (err) {
    if (err.code === "ENOENT") return null;
    throw err;
  }
}

function round1(v) {
  return Math.round(v * 10) / 10;
}

/** 经纬度保留 6 位小数（≈0.1m 精度），防止方位失真 */
function round6(v) {
  return Math.round(v * 1e6) / 1e6;
}

const pointsSrc = await readJson(SRC_ROUTE);
const wpSrc = await readJson(SRC_WAYPOINTS);
const meta = await readJson(SRC_META);

if (!pointsSrc) throw new Error("缺少 route-control-points.json");
if (!Array.isArray(pointsSrc) || pointsSrc.length < 100) {
  throw new Error(`控制点数量异常: ${pointsSrc && pointsSrc.length}`);
}
if (!Array.isArray(wpSrc) || wpSrc.length < 5) {
  throw new Error(`途经点数量异常: ${wpSrc && wpSrc.length}`);
}

// 十进位数保留 1 位；world x/y/z 保留 1 位（与设计源一致）
const points = pointsSrc.map((p, i) => ({
  lat: round6(p.lat),
  lon: round6(p.lon),
  x: round1(p.world[0]),
  y: round1(p.world[1]),
  z: round1(p.world[2]),
}));

const milestones = wpSrc.map((wp) => {
  const kind = KIND_BY_ID[wp.id] ?? "waypoint";
  return {
    id: wp.id,
    name: wp.label,
    kind,
    lat: round6(wp.lat),
    lon: round6(wp.lon),
    refM: wp.alt_ref_m,
    demM: round1(wp.dem_m),
    x: round1(wp.world[0]),
    y: round1(wp.world[1]),
  };
});

const baseM = meta ? meta.elevation_min_m : FALLBACK_BASE_M;

const payload = {
  schemaVersion: 1,
  id: "everest-south-col",
  name: "Everest 南坡攀登路线（South Col / 大本营 — 峰顶）",
  geodetic: "lonlat-wgs84",
  terrain: {
    baseM: baseM,
    baseMNote: meta
      ? "来自 everest-terrain-metadata.json elevation_min_m"
      : `回落缓存常数 ${FALLBACK_BASE_M}（见 SOURCE.md §DEM）`,
    units: "m",
  },
  points,
  milestones,
  provenance: [
    `design/world/everest-3d/route/route-control-points.json（${points.length} 控制点）`,
    `design/world/everest-3d/route/waypoints.json（${milestones.length} 里程碑）`,
    "由 scripts/routes/sync-everest-route.mjs 同步，未做任何距离计算",
  ],
};

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, JSON.stringify(payload, null, 2) + "\n", "utf8");

// 微信运行时不能 require(.json) 作为模块（loader 会把 require("./south-col.json")
// 变成寻找 south-col.json.js）。因此同步一份 .ts 模块供 tsc 编译为 .js，这是 runtime 唯一读入口。
const TS_HEADER = `/**
 * AUTO-GENERATED by scripts/routes/sync-everest-route.mjs — 请勿手改。
 * 同步自 design/world/everest-3d/route，与 south-col.json 同源同形。
 * 微信运行时不能 require .json 模块，因此以 .ts 模块承载同量数据。
 */
import type { RouteGeometryData } from "../../../types/expedition";

/** 强类型化（宽松断言）的静态路线数据。JSON 与 TS 字面量类型有微小差异，属预期。 */
export const SOUTH_COL_ROUTE: RouteGeometryData =`;
const ts = `${TS_HEADER} ${JSON.stringify(payload, null, 2)} as unknown as RouteGeometryData;\n`;
await writeFile(OUT_TS, ts, "utf8");

console.log(`[sync] wrote ${OUT}`);
console.log(`[sync] wrote ${OUT_TS}`);
console.log(`  points=${points.length} milestones=${milestones.length} baseM=${baseM}`);
console.log(`  first point: ${points[0].lat}, ${points[0].lon}, x=${points[0].x}`);
console.log(`  last  point: ${points.at(-1).lat}, ${points.at(-1).lon} x=${points.at(-1).x}`);
console.log(`  milestones ids: ${milestones.map((m) => `${m.id}(${m.kind})`).join(" ")}`);