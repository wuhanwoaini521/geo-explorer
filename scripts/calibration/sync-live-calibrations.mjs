// 同步 Everest LIVE 照片校准数据：design/world/everest-live/calibration/ → 运行时模块。
//
// 说明（对应 §30 / §31 / §47）：
//  - dev 工具（tools/everest-route-calibrator）生成 design/…/calibration/<scene>.json
//    （CalibrationReportV1，route[] 已投影 + 可见性标注）；
//  - 微信运行时不能 require(.json) 作为模块（loader 会把 require("./x.json")
//    变成查找 x.json.js），且生产不依赖 dev viewer / localhost / Python（§39）。
//    因此本脚本把校准 JSON「搬运 + 降维」成 RuntimeSceneCalibration 类型的 .ts
//    模块，是 runtime 唯一数据入口 —— 校准 JSON 仍是设计层唯一真相。
//  - 不做任何计算：route/waypoints 原样透传（仅对 u/v 做确定性舍入），
//    info 文案由 status 派生（§40：REPRESENTATIVE 不写“精准路线”）。
//
// 运行：
//   node scripts/calibration/sync-live-calibrations.mjs
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const SRC_DIR = join(ROOT, "design/world/everest-live/calibration");
const OUT_DIR = join(ROOT, "miniprogram/data/calibrations/everest");

/** 评审状态 → 运行时 info.note（§40 文案：REPRESENTATIVE 不说“精准路线”） */
const NOTE_BY_STATUS = {
  VERIFIED:
    "真实珠峰影像 · 路线：已验证投影（回报精度与视差校验全部达标）",
  CALIBRATED:
    "真实珠峰影像 · 路线：校准投影（经人工 landmarks 求解，误差达标）",
  REPRESENTATIVE:
    "真实珠峰影像 · 代表性视角（未做精确像素投影，routeOverlay 关闭）",
  UNAVAILABLE:
    "真实珠峰影像 · 视觉背景（无路线投影数据）",
};

function round(v, digits) {
  if (typeof v !== "number" || !Number.isFinite(v)) return v;
  const p = 10 ** digits;
  return Math.round(v * p) / p;
}

/** 只保留 RuntimeSceneCalibration 运行时视图（丢弃 solver 中间量） */
function toRuntimeView(report) {
  return {
    sceneId: report.sceneId,
    assetId: report.assetId,
    status: report.status,
    route: (report.route ?? []).map((p) => ({
      routeIndex: p.routeIndex,
      u: round(p.u, 6),
      v: round(p.v, 6),
      visibility: p.visibility,
    })),
    waypoints: (report.waypoints ?? []).map((w) => ({
      waypointId: w.waypointId,
      u: round(w.u, 6),
      v: round(w.v, 6),
    })),
    info: {
      status: report.status,
      medianPx: round(report.reprojection?.medianPx ?? 0, 3),
      maxValidationPx: round(report.reprojection?.maxValidationPx ?? 0, 3),
      note: NOTE_BY_STATUS[report.status] ?? String(report.status),
    },
  };
}

const TS_HEADER = `/**
 * AUTO-GENERATED by scripts/calibration/sync-live-calibrations.mjs — 请勿手改。
 * 同步自 design/world/everest-live/calibration/<SCENE>.json（CalibrationReport 唯一真相源）。
 * 微信运行时不能 require .json 模块，因此以 .ts 模块承载同量数据；本文件只降维
 * 成 RuntimeSceneCalibration 运行时视图（route 已投影 + 可见性）。
 */
import type { RuntimeSceneCalibration } from "../../../types/calibration";

`;

async function readJson(path) {
  try {
    return JSON.parse(await readFile(path, "utf8"));
  } catch (err) {
    if (err.code === "ENOENT") return null;
    throw err;
  }
}

const entries = (await readdir(SRC_DIR))
  .filter((f) => f.endsWith(".json"))
  .sort();

const scenes = [];
for (const f of entries) {
  const report = await readJson(join(SRC_DIR, f));
  if (!report || report.schemaVersion !== 1) {
    throw new Error(`跳过/无效校准 ${f}`);
  }
  const runtime = toRuntimeView(report);
  // sceneId 与文件名一致性护栏（防拷错）
  if (runtime.sceneId !== runtime.assetId) {
    // assetId 允许不同名（同一照片可对应多场景），不强校验。
  }
  scenes.push({ sceneId: runtime.sceneId, runtime, file: f });
}

if (scenes.length === 0) throw new Error("没有找到校准 JSON，先跑 CLI representative");

await mkdir(OUT_DIR, { recursive: true });

for (const { sceneId, runtime, file } of scenes) {
  const out = join(OUT_DIR, `${sceneId}-calibration.ts`);
  const literal = JSON.stringify(runtime, null, 2);
  const ts = `${TS_HEADER.replace(/<SCENE>/g, file.replace(/\.json$/, ""))}export const CALIBRATION: RuntimeSceneCalibration = ${literal} as RuntimeSceneCalibration;\n`;
  await writeFile(out, ts, "utf8");
  console.log(`[sync] ${file} → ${sceneId}-calibration.ts`);
}

// 索引模块：场景 id → 校准（无校准返回 null，由引擎降级为无路线）
const imports = scenes
  .map((s) => `import { CALIBRATION as ${s.sceneId.replace(/-/g, "_")} } from "./${s.sceneId}-calibration";`)
  .join("\n");
const mapLines = scenes
  .map((s) => `  "${s.sceneId}": ${s.sceneId.replace(/-/g, "_")},`)
  .join("\n");
const indexTs = `/**
 * AUTO-GENERATED by scripts/calibration/sync-live-calibrations.mjs — 请勿手改。
 * 运行时校准注册表：sceneId → RuntimeSceneCalibration。
 * 缺省场景（未校准）返回 null —— 引擎据此决定不画路线（§31 REPRESENTATIVE 同理）。
 */
import type { RuntimeSceneCalibration } from "../../../types/calibration";
${imports}

/** 全部已同步校准（key = LIVE scene id） */
export const EVEREST_LIVE_CALIBRATIONS: Record<string, RuntimeSceneCalibration> = {
${mapLines}
};

/** 取某 LIVE 场景的校准（未校准/无校准 → null，调用方据此降级） */
export function calibrationForScene(sceneId: string): RuntimeSceneCalibration | null {
  return EVEREST_LIVE_CALIBRATIONS[sceneId] ?? null;
}
`;
await writeFile(join(OUT_DIR, "index.ts"), indexTs, "utf8");
console.log(`[sync] wrote index.ts (${scenes.length} scenes)`);