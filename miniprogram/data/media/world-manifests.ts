/* ---------------- 校验侧守门：重复 media id 一律 ERROR（PHASE 11） ---------------- */

import { validateMediaManifest } from "../../engine/validate-expedition";

export function validateRuntimeManifests(): string[] {
  const issues: string[] = [];
  for (const m of RUNTIME_MANIFESTS) {
    for (const i of validateMediaManifest(m).issues) {
      if (i.level === "error") issues.push(`${m.id}: ${i.path} ${i.message}`);
    }
  }
  // 跨清单重复 id 检测（首个声明者胜出是查询行为，但正式内容不允许冲突声明）
  const seen = new Map<string, string>();
  for (const m of RUNTIME_MANIFESTS) {
    for (const a of m.assets) {
      if (seen.has(a.id)) {
        issues.push(`duplicate-media-id: ${a.id} 同时声明于 ${seen.get(a.id)} 与 ${m.id}`);
      } else {
        seen.set(a.id, m.id);
      }
    }
  }
  return issues;
}
